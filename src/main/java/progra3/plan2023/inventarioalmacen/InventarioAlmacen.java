    // Pasa los datos de la fila seleccionada a los campos del formulario
    private void cargarSeleccion() {
        int fila = tblInventario.getSelectedRow();
        if (fila < 0) {
            return;
        }

        Producto p = productos.get(tblInventario.getValueAt(fila, 0).toString());
        if (p == null) {
            return;
        }

        txtNombre.setText(p.getNombre());
        txtMarca.setText(p.getMarca());
        txtTamano.setText(p.getTamano());
        txtPeso.setText(p.getPeso());
        txtCantidad.setText(String.valueOf(p.getCantidad()));
        cmbProducto.setSelectedItem(p.getNombre());
    }

    // Lee y valida los campos del formulario. Devuelve null si algo esta mal.
    private Producto leerProductoDelFormulario() {
        String nombre = txtNombre.getText().trim();
        String marca = txtMarca.getText().trim();
        String tamano = txtTamano.getText().trim();
        String peso = txtPeso.getText().trim();
        String textoCantidad = txtCantidad.getText().trim();

        if (nombre.isEmpty()) {
            mostrarError("Debe ingresar el nombre del producto.");
            txtNombre.requestFocus();
            return null;
        }
        if (marca.isEmpty()) {
            mostrarError("Debe ingresar la marca del producto.");
            txtMarca.requestFocus();
            return null;
        }
        if (tamano.isEmpty()) {
            mostrarError("Debe ingresar el tamaño del producto.");
            txtTamano.requestFocus();
            return null;
        }
        if (peso.isEmpty()) {
            mostrarError("Debe ingresar el peso del producto.");
            txtPeso.requestFocus();
            return null;
        }
        if (textoCantidad.isEmpty()) {
            mostrarError("Debe ingresar la cantidad del producto.");
            txtCantidad.requestFocus();
            return null;
        }

        // El caracter | separa los datos en el archivo, por eso no se permite
        if (nombre.contains("|") || marca.contains("|")
                || tamano.contains("|") || peso.contains("|")) {
            mostrarError("Los datos no pueden contener el carácter |.");
            return null;
        }

        int cantidad;
        try {
            cantidad = Integer.parseInt(textoCantidad);
        } catch (NumberFormatException error) {
            mostrarError("La cantidad debe ser un número entero.");
            txtCantidad.requestFocus();
            return null;
        }
        if (cantidad < 0) {
            mostrarError("La cantidad no puede ser negativa.");
            txtCantidad.requestFocus();
            return null;
        }

        return new Producto(nombre, marca, tamano, peso, cantidad);
    }

    // Devuelve el producto con ese nombre (sin importar mayusculas) o null
    private Producto buscarPorNombre(String nombre) {
        for (Producto p : productos.values()) {
            if (p.getNombre().equalsIgnoreCase(nombre)) {
                return p;
            }
        }
        return null;
    }

