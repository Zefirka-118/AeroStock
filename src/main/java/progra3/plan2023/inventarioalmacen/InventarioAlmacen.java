    // Agrega un producto nuevo con los datos del formulario
    private void agregarProducto() {
        Producto nuevo = leerProductoDelFormulario();
        if (nuevo == null) {
            return;
        }

        if (buscarPorNombre(nuevo.getNombre()) != null) {
            mostrarError("Ya existe un producto con ese nombre.");
            txtNombre.requestFocus();
            return;
        }

        productos.put(nuevo.getNombre(), nuevo);

        guardarArchivo();
        mostrarProductos();
        actualizarComboProductos();
        limpiarCampos();

        mostrarMensaje("Producto agregado correctamente.");
    }

    // Modifica el producto que esta seleccionado en la tabla
    private void modificarProducto() {
        int fila = tblInventario.getSelectedRow();
        if (fila < 0) {
            mostrarError("Seleccione un producto de la tabla para modificarlo.");
            return;
        }
        String nombreOriginal = tblInventario.getValueAt(fila, 0).toString();

        Producto nuevo = leerProductoDelFormulario();
        if (nuevo == null) {
            return;
        }

        Producto repetido = buscarPorNombre(nuevo.getNombre());
        if (repetido != null && !repetido.getNombre().equals(nombreOriginal)) {
            mostrarError("Ya existe otro producto con ese nombre.");
            txtNombre.requestFocus();
            return;
        }

        // Se arma el mapa de nuevo para conservar el orden aunque cambie el nombre
        Map<String, Producto> copia = new LinkedHashMap<>();
        for (Producto p : productos.values()) {
            if (p.getNombre().equals(nombreOriginal)) {
                copia.put(nuevo.getNombre(), nuevo);
            } else {
                copia.put(p.getNombre(), p);
            }
        }
        productos.clear();
        productos.putAll(copia);

        guardarArchivo();
        mostrarProductos();
        actualizarComboProductos();
        limpiarCampos();

        mostrarMensaje("Producto modificado correctamente.");
    }

    // Elimina el producto seleccionado en la tabla (con confirmacion)
    private void eliminarProducto() {
        int fila = tblInventario.getSelectedRow();
        if (fila < 0) {
            mostrarError("Seleccione un producto de la tabla para eliminarlo.");
            return;
        }
        String nombre = tblInventario.getValueAt(fila, 0).toString();

        int respuesta = JOptionPane.showConfirmDialog(this,
                "¿Está seguro de eliminar este producto?\n" + nombre,
                "Confirmar eliminación",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.QUESTION_MESSAGE);

        if (respuesta != JOptionPane.YES_OPTION) {
            return;
        }

        productos.remove(nombre);

        guardarArchivo();
        mostrarProductos();
        actualizarComboProductos();
        limpiarCampos();

        mostrarMensaje("Producto eliminado correctamente.");
    }

    // Busca por nombre. Si hay varias coincidencias, cada clic pasa a la siguiente.
    private void buscarProducto() {
        String texto = txtBuscar.getText().trim().toLowerCase();
        if (texto.isEmpty()) {
            mostrarError("Debe ingresar el nombre del producto que desea buscar.");
            txtBuscar.requestFocus();
            return;
        }
        // De 561 a 572: búsqueda con navegación cíclica
        // Recorre todas las filas de la tabla empezando desde la que sigue a la actual.
        // Cuando llega al final, vuelve al inicio (navegación circular).
        // Si encuentra una fila cuyo nombre contiene el texto buscado, la selecciona,
        // desplaza la vista hacia ella, carga sus datos en el formulario y termina.
        // Si no encuentra nada, el bucle termina sin cambiar la selección.
        int total = tblInventario.getRowCount();
        int inicio = tblInventario.getSelectedRow();

        for (int k = 1; k <= total; k++) {
            int fila = (inicio + k) % total;
            String nombre = tblInventario.getValueAt(fila, 0).toString().toLowerCase();

            if (nombre.contains(texto)) {
                tblInventario.setRowSelectionInterval(fila, fila);
                tblInventario.scrollRectToVisible(tblInventario.getCellRect(fila, 0, true));
                cargarSeleccion();
                return;
            }
        }

        mostrarError("No se encontró ningún producto con ese nombre.");
    }

