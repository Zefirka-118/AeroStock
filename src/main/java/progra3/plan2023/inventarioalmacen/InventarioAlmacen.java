    // Vuelve a llenar la tabla con los productos
    private void mostrarProductos() {
        DefaultTableModel modelo = (DefaultTableModel) tblInventario.getModel();
        modelo.setRowCount(0);

        for (Producto p : productos.values()) {
            modelo.addRow(new Object[]{
                p.getNombre(),
                p.getMarca(),
                p.getTamano(),
                p.getPeso(),
                p.getCantidad()
            });
        }
    }

    // Vuelve a llenar el combo del movimiento y conserva la seleccion si se puede
    private void actualizarComboProductos() {
        Object seleccionado = cmbProducto.getSelectedItem();

        cmbProducto.removeAllItems();
        for (String nombre : productos.keySet()) {
            cmbProducto.addItem(nombre);
        }

        if (seleccionado != null && productos.containsKey(seleccionado.toString())) {
            cmbProducto.setSelectedItem(seleccionado);
        } else {
            cmbProducto.setSelectedIndex(-1);
        }
    }

