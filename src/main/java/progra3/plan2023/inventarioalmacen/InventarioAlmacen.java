    // Registra una ENTRADA o una SALIDA del producto seleccionado en el combo
    private void registrarMovimiento(String tipo) {
        String nombreProducto = (String) cmbProducto.getSelectedItem();
        if (nombreProducto == null) {
            mostrarError("Debe seleccionar un producto.");
            cmbProducto.requestFocus();
            return;
        }

        String textoCantidad = txtCantidadMov.getText().trim();
        if (textoCantidad.isEmpty()) {
            mostrarError("Debe ingresar la cantidad del movimiento.");
            txtCantidadMov.requestFocus();
            return;
        }

        int cantidad;
        try {
            cantidad = Integer.parseInt(textoCantidad);
        } catch (NumberFormatException error) {
            mostrarError("La cantidad debe ser un número entero.");
            txtCantidadMov.requestFocus();
            return;
        }
        if (cantidad <= 0) {
            mostrarError("La cantidad debe ser mayor que cero.");
            txtCantidadMov.requestFocus();
            return;
        }

        String persona = txtPersona.getText().trim();
        if (persona.isEmpty()) {
            mostrarError("Debe ingresar quién realiza el movimiento.");
            txtPersona.requestFocus();
            return;
        }
        if (persona.contains("|")) {
            mostrarError("El nombre no puede contener el carácter |.");
            txtPersona.requestFocus();
            return;
        }

        Producto producto = productos.get(nombreProducto);
        if (producto == null) {
            mostrarError("El producto seleccionado ya no existe.");
            actualizarComboProductos();
            return;
        }

        int stockAnterior = producto.getCantidad();
        int stockNuevo;

        if (tipo.equals("ENTRADA")) {
            if (cantidad > Integer.MAX_VALUE - stockAnterior) {
                mostrarError("La cantidad es demasiado grande.");
                return;
            }
            stockNuevo = stockAnterior + cantidad;
        } else {
            if (cantidad > stockAnterior) {
                mostrarError("No hay suficiente stock disponible.\nStock actual: " + stockAnterior);
                return;
            }
            stockNuevo = stockAnterior - cantidad;
        }

        producto.setCantidad(stockNuevo);

        // El ID y la fecha los genera el programa
        int id = siguienteId;
        String fechaHora = LocalDateTime.now().format(formatoFecha);
        movimientos.add(new Movimiento(id, tipo, producto.getNombre(), cantidad, persona, fechaHora));
        siguienteId++;

        guardarArchivo();
        mostrarProductos();
        txtCantidadMov.setText("");

        String nombreTipo = tipo.equals("ENTRADA") ? "Entrada" : "Salida";
        mostrarMensaje(nombreTipo + " registrada correctamente.\n"
                + "Producto: " + producto.getNombre() + "\n"
                + "Stock anterior: " + stockAnterior + "\n"
                + nombreTipo + ": " + cantidad + "\n"
                + "Stock nuevo: " + stockNuevo + "\n"
                + "ID del movimiento: " + id);
    }

