    // Formato del archivo:
    //   PRODUCTOS
    //   nombre|marca|tamano|peso|cantidad
    //
    //   MOVIMIENTOS
    //   id|tipo|producto|cantidad|persona|fecha y hora
    private void guardarArchivo() {
        try (BufferedWriter escritor = Files.newBufferedWriter(archivo, StandardCharsets.UTF_8)) {

            escritor.write("PRODUCTOS");
            escritor.newLine();

            for (Producto p : productos.values()) {
                escritor.write(p.getNombre()
                        + "|" + p.getMarca()
                        + "|" + p.getTamano()
                        + "|" + p.getPeso()
                        + "|" + p.getCantidad());
                escritor.newLine();
            }

            escritor.newLine();
            escritor.write("MOVIMIENTOS");
            escritor.newLine();

            for (Movimiento m : movimientos) {
                escritor.write(m.getId()
                        + "|" + m.getTipo()
                        + "|" + m.getProducto()
                        + "|" + m.getCantidad()
                        + "|" + m.getPersona()
                        + "|" + m.getFechaHora());
                escritor.newLine();
            }

        } catch (IOException error) {
            JOptionPane.showMessageDialog(this,
                    "No se pudo guardar la información.\n" + error.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    // Si el archivo no existe, usa los 45 productos iniciales y lo crea
    private void cargarArchivo() {
        if (!Files.exists(archivo)) {
            cargarProductosIniciales();
            guardarArchivo();
            return;
        }

        try (BufferedReader lector = Files.newBufferedReader(archivo, StandardCharsets.UTF_8)) {

            String seccion = "";
            String linea;

            while ((linea = lector.readLine()) != null) {

                // Quita la marca BOM que algunos editores agregan al inicio
                if (linea.startsWith("\uFEFF")) {
                    linea = linea.substring(1);
                }
                linea = linea.trim();

                if (linea.isEmpty()) {
                    continue;
                }
                if (linea.equals("PRODUCTOS") || linea.equals("MOVIMIENTOS")) {
                    seccion = linea;
                    continue;
                }

                String[] datos = linea.split("\\|", -1);

                try {
                    if (seccion.equals("PRODUCTOS") && datos.length == 5) {
                        Producto p = new Producto(datos[0], datos[1], datos[2], datos[3],
                                Integer.parseInt(datos[4]));
                        productos.put(p.getNombre(), p);

                    } else if (seccion.equals("MOVIMIENTOS") && datos.length == 6) {
                        int id = Integer.parseInt(datos[0]);
                        movimientos.add(new Movimiento(id, datos[1], datos[2],
                                Integer.parseInt(datos[3]), datos[4], datos[5]));

                        // Asi el ID no se pierde al cerrar y abrir el programa
                        if (id >= siguienteId) {
                            siguienteId = id + 1;
                        }
                    }
                } catch (NumberFormatException error) {
                    // Linea con numeros invalidos: se ignora
                }
            }

        } catch (IOException error) {
            JOptionPane.showMessageDialog(this,
                    "No se pudo cargar la información.\n" + error.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

